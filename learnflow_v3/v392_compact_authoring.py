def creative_witness(p,transformed):
    """Verify candidate is materially distinct from preserved HOST_TEST fixture.

    Differing captions alone is authorship of narration, NOT fully autonomous
    visual storytelling. Require actual scene focus/composition/motion delta.
    """
    b=host_test_baseline()
    changed=sum(transformed["beats"][i]["caption"]!=b["beats"][i]["caption"] for i in range(5))
    visual_changes=(
      transformed["visual_thinker"]["composition"]!=b["visual_thinker"]["composition"]
      or transformed["motion_director"]["method"]!=b["motion_director"]["method"]
      or any(transformed["beats"][i]["visual_focus"]!=b["beats"][i]["visual_focus"]
             for i in range(5))
    )
    if changed<2:fail("INSUFFICIENT_ORIGINAL_NARRATION")
    if not visual_changes:fail("NO_ORIGINAL_VISUAL_DECISION")
    return {"changed_narration_beats":changed,
            "visual_directive_differs_from_host":True,
            "model_storyboard_sha256":digest(p),
            "compiled_source_sha256":digest(transformed),
            "host_ledger_sha256":LEDGER_SHA,
            "quality_limit":"SEMANTICALLY_CONSTRAINED_NO_HUMAN_REVIEW",
            "independent_learning_benefit":"NOT_MEASURED"}
