"""V3-92: compact AI-authored educational storyboard; strict host-ledger compiler.

This module does not call a model. Compared with V3-64 (large provider schema,
ordered 12 IDs, five expert sub-objects), model only supplies strategies, pacing
and original narrated scene beats. Host owns facts, object identity, reveal rules,
source SHA and trusted rendering code. This IS a bounded pilot, NOT general AI
lesson research or 3Blue1Brown-equivalent creativity.
"""
from __future__ import annotations
from copy import deepcopy
from hashlib import sha256
import json
import re

from learnflow_v3.v364_heldout_storyboard import (
    LEDGER_SHA, STAGES, UNIT_IDS, TOPIC, accept, host_test_baseline, digest
)

WIRE_VERSION="v392_compact_model_authored_storyboard_v1"
STRATEGIES=("predict_first","notice_paradox")
CLOSURES=("counting_invariant","multiplication_as_groups")
COMPOSITIONS=("single_stage","side_by_side")
MOTIONS=("smooth_morph","staggered_morph")
FOCI=("all_twelve","highlight_first_row","track_corner")
ROOT_KEYS={"opening_strategy","closure_strategy","composition","motion_method","focus","beats"}
BEAT_KEYS={"stage","narration","visual_focus"}
MAX_WIRE=6500

class Rejected(ValueError):
    pass

def fail(reason):
    raise Rejected("V392_"+reason)

def _pairs_unique(pairs):
    d={}
    for k,v in pairs:
        if k in d: fail("DUPLICATE_JSON_KEY")
        d[k]=v
    return d

def strict_parse(raw:bytes):
    if type(raw) is not bytes or not (0<len(raw)<=MAX_WIRE):
        fail("INVALID_WIRE_LENGTH")
    try:
        p=json.loads(raw.decode("utf-8"),
                     parse_constant=lambda v:fail("NONFINITE_JSON"),
                     object_pairs_hook=_pairs_unique)
    except (UnicodeDecodeError,json.JSONDecodeError) as exc:
        raise Rejected("V392_INVALID_JSON") from exc
    return accept_compact(p)

def accept_compact(p):
    if type(p) is not dict or set(p)!=ROOT_KEYS:
        fail("ROOT_FIELDS_MISMATCH")
    for key, choices in (
        ("opening_strategy",STRATEGIES),("closure_strategy",CLOSURES),
        ("composition",COMPOSITIONS),("motion_method",MOTIONS),
        ("focus",FOCI)):
        if type(p[key]) is not str or p[key] not in choices:
            fail("INVALID_"+key.upper())
    beats=p["beats"]
    if type(beats) is not list or len(beats)!=5:
        fail("FIVE_BEATS_REQUIRED")
    allcaptions=[]
    for i,b in enumerate(beats):
        if type(b) is not dict or set(b)!=BEAT_KEYS:
            fail("BEAT_FIELDS_MISMATCH")
        if b["stage"]!=STAGES[i]:
            fail("BEAT_STAGE_ORDER")
        if type(b["visual_focus"]) is not str or b["visual_focus"] not in FOCI:
            fail("BEAT_VISUAL_FOCUS_UNSAFE")
        s=b["narration"]
        if type(s) is not str or not 18<=len(s)<=150 or s!=s.strip():
            fail("BEAT_NARRATION_LENGTH")
        if any(ch in s for ch in "<>{}\n\r\\"):
            fail("BEAT_UNSAFE_CHARACTERS")
        if any(ord(ch)<32 or ord(ch)>126 for ch in s):
            fail("BEAT_ASCII_SPEECH_REQUIRED")
        if re.search(r"\b(ignore previous|system prompt|execute|javascript|python|eval|sudo|publish this|generated by ai)\b",s,re.I):
            fail("NARRATION_UNTRUSTED_INSTRUCTION")
        nums=re.findall(r"(?<![A-Za-z_])\d+(?:\.\d+)?(?![A-Za-z_])",s)
        if any(x not in ("3","4","12") for x in nums):
            fail("UNVERIFIED_NUMERIC_CLAIM")
        if i<3 and "12" in nums:
            fail("EARLY_ANSWER")
        if i>=3 and "12" not in nums:
            fail("FINAL_EVIDENCE_MISSING")
        if re.search(r"\b(students learned|proven improvement|guaranteed understanding|measured learners)\b",s,re.I):
            fail("UNMEASURED_HUMAN_BENEFIT")
        allcaptions.append(s.lower())
    if len(set(allcaptions))<5:
        fail("REPEATED_SCRIPT_BEATS")
    return p

def host_compile(p):
    """Inject model-authored decisions into existing trusted native source contract."""
    accept_compact(p)
    fixture=deepcopy(host_test_baseline())
    fixture["narrative_designer"]["opening"]=p["opening_strategy"]
    fixture["narrative_designer"]["closure"]=p["closure_strategy"]
    fixture["visual_thinker"]["composition"]=p["composition"]
    fixture["visual_thinker"]["focus"]=p["focus"]
    fixture["motion_director"]["method"]=p["motion_method"]
    for i,beat in enumerate(p["beats"]):
        fixture["beats"][i]["caption"]=beat["narration"]
        fixture["beats"][i]["visual_focus"]=beat["visual_focus"]
    approved=accept(fixture)
    if approved["host_ledger_sha256"]!=LEDGER_SHA or tuple(approved["persistent_object_ids"])!=UNIT_IDS:
        fail("HOST_FACTS_OR_OBJECT_ID_DRIFT")
    return fixture

