def compiled_event_windows(lesson:SemanticLesson, durations:list[float])->list[dict]:
    if len(durations) != len(lesson.beats) or any(not 2 <= d <= 20 for d in durations):
        raise Blocked("V344_MEASURED_BEAT_DURATION_INVALID")
    boundaries=[]; base=0.
    for i,(beat,seconds) in enumerate(zip(lesson.beats,durations)):
        for e in beat.events:
            boundaries.append({"beat":i+1,"kind":e.kind,"target":e.target,"source":e.source,
               "start_seconds":round(base+seconds*e.at,4),
               "end_seconds":round(base+seconds*(e.at+e.span),4)})
        base+=seconds
    return boundaries


def compile_manim(lesson:SemanticLesson, durations:list[float])->str:
    # Pure host-compiled finite code; source never comes from model-provided Python.
    schedule = compiled_event_windows(lesson,durations)
    lines=["# V3-44 HOST-CURATED SEMANTIC EVENT COUNTERFACTUAL; NOT MODEL-AUTHORED",
           "from manim import *","class GeneratedLesson(Scene):",
           "    def construct(self):",
           "        self.camera.background_color = '#000000'"]
    for t in lesson.tiles:
        lines.append(f"        {t.id} = Rectangle(width={t.width:.3f},height={t.height:.3f},"
                     f"color={PALETTE[t.color]!r},fill_opacity=0.62).move_to([{t.x:.3f},{t.y:.3f},0])")
    for l in lesson.labels:
        lines.append(f"        {l.id} = Text({l.text!r},font='CMU Serif',font_size=32,"
                     f"color={PALETTE[l.color]!r}).scale_to_fit_width({min(8.,max(.5,len(l.text)*.23)):.2f})"
                     f".move_to([{l.x:.3f},{l.y:.3f},0])")
    parts={p.id:p for p in lesson.partitions}
    for p in lesson.partitions:
        refs=", ".join(p.part_ids)
        lines.append(f"        {p.id} = VGroup({refs})")
    t=0.
    for beat,duration in zip(lesson.beats,durations):
        lines.append(f"        # V344 BEAT_AUDIO_START {t:.5f} DURATION {duration:.5f}")
        local=0.
        for event in beat.events:
            before=event.at*duration-local
            if before>0.00001:
                lines.append(f"        self.wait({before:.5f})")
            seconds=event.span*duration
            target=event.target
            if event.kind == "reveal_partition":
                tiles=parts[target].part_ids
                animations=", ".join(f"FadeIn({i},shift=.10*UP)" for i in tiles)
                lines.append(f"        self.play(LaggedStart({animations},lag_ratio=0.04),run_time={seconds:.5f})")
            elif event.kind == "morph_partition":
                src=parts[event.source]
                dst=parts[target]
                factor=len(dst.part_ids)//len(src.part_ids)
                anims=", ".join(f"TransformFromCopy({src.part_ids[i//factor]},{pid})"
                        for i,pid in enumerate(dst.part_ids))
                lines.append(f"        self.play(AnimationGroup({anims},lag_ratio=0.03),run_time={seconds:.5f})")
            elif event.kind == "show_label":
                lines.append(f"        self.play(FadeIn({target}),run_time={seconds:.5f})")
            elif event.kind == "emphasize":
                lines.append(f"        self.play(Indicate({target},color=YELLOW,scale_factor=1.08),run_time={seconds:.5f})")
            else:
                lines.append(f"        self.wait({seconds:.5f})")
            local=duration*(event.at+event.span)
        remainder=duration-local
        if remainder>0.00001:
            lines.append(f"        self.wait({remainder:.5f})")
        t+=duration
    # Manim frame discretization may finish a few frames before the
    # frame-aligned spoken WAV despite equal nominal source durations.
    # Make video safely LONGER than the full audio and let -shortest mux
    # trim the final no-content-changing hold at real WAV duration.
    # This host-only slack is outside ALL semantic event anchors.
    lines.append("        # V344 VIDEO-ONLY SAFETY TAIL: TRIM AT ORIGINAL AUDIO END")
    lines.append("        self.wait(0.80000)")
    code="\n".join(lines)+"\n"
    if any(x in code for x in ("__import__","eval(","exec(","os.system","subprocess","import os","import sys")):
        raise Blocked("V344_COMPILER_SAFETY_VIOLATION")
    return code


def verify_source_artifact(folder:Path)->CreativeScene:
    from hashlib import sha256
    folder=folder.resolve()
    for filename,expected in (
        ("scene_plan.json",SOURCE_SCENE_SHA),
        ("creative_manim_with_audio.mp4",SOURCE_VIDEO_SHA)):
        file=folder/filename
        if not file.is_file() or file.is_symlink() or sha256(file.read_bytes()).hexdigest()!=expected:
            raise Blocked("V344_SOURCE_MODEL_ARTIFACT_TAMPERED:" + filename)
    try:
        scene=CreativeScene.model_validate_json((folder/"scene_plan.json").read_text())
    except Exception:
        raise Blocked("V344_REAL_SCENE_INVALID") from None
    if scene.model_author!="openai/gpt-6-luna":
        raise Blocked("V344_FALSE_REAL_SCENE_AUTHOR")
    return scene
