class Tile(BaseModel):
    model_config = ConfigDict(extra="forbid")
    id: str = Field(pattern=r"^[a-z][a-z0-9_]{0,22}$")
    x: float = Field(ge=-5.7, le=5.7)
    y: float = Field(ge=-2.55, le=2.55)
    width: float = Field(gt=.1, le=4)
    height: float = Field(gt=.1, le=2.4)
    color: Literal["TEAL", "GREY", "BLUE", "GREEN", "ORANGE", "YELLOW", "WHITE"]
    @model_validator(mode="after")
    def safe(self):
        if keyword.iskeyword(self.id):
            raise ValueError("V344_UNSAFE_TILE_ID")
        return self


class Label(BaseModel):
    model_config = ConfigDict(extra="forbid")
    id: str = Field(pattern=r"^[a-z][a-z0-9_]{0,22}$")
    x: float = Field(ge=-5.7, le=5.7)
    y: float = Field(ge=-2.55, le=2.55)
    text: str = Field(min_length=1, max_length=65)
    color: Literal["WHITE", "TEAL", "YELLOW", "BLUE"]
    @model_validator(mode="after")
    def safe(self):
        if keyword.iskeyword(self.id) or any(ord(c) < 32 for c in self.text):
            raise ValueError("V344_UNSAFE_LABEL")
        return self


class Partition(BaseModel):
    model_config = ConfigDict(extra="forbid")
    id: str = Field(pattern=r"^[a-z][a-z0-9_]{0,22}$")
    part_ids: list[str] = Field(min_length=2, max_length=12)
    shaded_ids: list[str] = Field(min_length=1, max_length=11)
    numerator: int = Field(ge=1, le=12)
    denominator: int = Field(ge=2, le=12)


class Relation(BaseModel):
    model_config = ConfigDict(extra="forbid")
    source: str
    target: str
    multiply_by: int = Field(ge=2, le=8)
    proof_label_id: str
    # The symbolic expression must be ACTUALLY visible in the renderer.


class Event(BaseModel):
    model_config = ConfigDict(extra="forbid")
    kind: Literal["reveal_partition", "morph_partition", "show_label",
                  "emphasize", "hold"]
    target: str = ""
    source: str = ""
    at: float = Field(ge=0, lt=1)
    span: float = Field(gt=0, le=.6)
    @model_validator(mode="after")
    def valid_args(self):
        if self.at + self.span > 1.000001:
            raise ValueError("V344_EVENT_OUTSIDE_SPOKEN_BEAT")
        if self.kind == "hold":
            if self.target or self.source:
                raise ValueError("V344_HOLD_WITH_REFERENCES")
        elif not self.target:
            raise ValueError("V344_EVENT_TARGET_MISSING")
        if self.kind == "morph_partition" and not self.source:
            raise ValueError("V344_MORPH_SOURCE_MISSING")
        if self.kind != "morph_partition" and self.source:
            raise ValueError("V344_UNEXPECTED_MORPH_SOURCE")
        return self


class TimedBeat(BaseModel):
    model_config = ConfigDict(extra="forbid")
    narration: str = Field(min_length=65, max_length=270)
    claim_ids: list[Literal["F1", "F2", "F3"]] = Field(min_length=1, max_length=3)
    events: list[Event] = Field(min_length=1, max_length=8)


def _whole_extent(part: Partition, tiles: dict[str, Tile]) -> tuple[float, float, float]:
    pieces = [tiles[i] for i in part.part_ids]
    lo_x = min(t.x - t.width/2 for t in pieces)
    hi_x = max(t.x + t.width/2 for t in pieces)
    lo_y = min(t.y - t.height/2 for t in pieces)
    hi_y = max(t.y + t.height/2 for t in pieces)
    bbox = (hi_x - lo_x) * (hi_y - lo_y)
    areas = [t.width*t.height for t in pieces]
    total = sum(areas)
    if not math.isclose(bbox, total, abs_tol=1e-5):
        raise ValueError("V344_PARTITION_GAPS_OR_OUTER_BOUNDS")
    if not all(math.isclose(a, total/part.denominator, rel_tol=.001) for a in areas):
        raise ValueError("V344_PARTITION_UNEQUAL_PARTS")
    for j, t in enumerate(pieces):
        for u in pieces[j+1:]:
            ox = min(t.x+t.width/2, u.x+u.width/2)-max(t.x-t.width/2, u.x-u.width/2)
            oy = min(t.y+t.height/2, u.y+u.height/2)-max(t.y-t.height/2, u.y-u.height/2)
            if ox > 1e-5 and oy > 1e-5:
                raise ValueError("V344_PARTITION_TILE_OVERLAP")
    return total, lo_x, hi_x


class SemanticLesson(BaseModel):
    model_config = ConfigDict(extra="forbid")
    title: str = Field(min_length=8, max_length=65)
    tiles: list[Tile] = Field(min_length=4, max_length=24)
    labels: list[Label] = Field(min_length=2, max_length=16)
    partitions: list[Partition] = Field(min_length=2, max_length=5)
    relations: list[Relation] = Field(min_length=1, max_length=4)
    beats: list[TimedBeat] = Field(min_length=4, max_length=4)
    provenance: Literal["HOST_CURATED_SEMANTIC_VISUAL_COUNTERFACTUAL_REUSED_REAL_NARRATION_NOT_MODEL_AUTHORED"]

    @model_validator(mode="after")
    def safe_semantic_graph(self):
        _unique = [x.id for x in self.tiles + self.labels + self.partitions]
        if len(_unique) != len(set(_unique)):
            raise ValueError("V344_DUPLICATE_IDS")
        tiles = {t.id:t for t in self.tiles}
        labels = {t.id:t for t in self.labels}
        parts = {p.id:p for p in self.partitions}
        for p in self.partitions:
            if len(p.part_ids) != p.denominator or len(p.shaded_ids) != p.numerator:
                raise ValueError("V344_FRACTION_COUNTS_MISMATCH")
            if len(set(p.part_ids)) != len(p.part_ids) or len(set(p.shaded_ids)) != len(p.shaded_ids):
                raise ValueError("V344_DUPLICATE_PART_REFERENCE")
            if set(p.shaded_ids) - set(p.part_ids) or set(p.part_ids) - set(tiles):
                raise ValueError("V344_PARTITION_DANGLING_TILE")
            if any(tiles[pid].color not in ("TEAL","BLUE","GREEN") for pid in p.shaded_ids):
                raise ValueError("V344_SHADED_COLOR_CONTRACT")
            if any(tiles[pid].color in ("TEAL","BLUE","GREEN") for pid in p.part_ids if pid not in p.shaded_ids):
                raise ValueError("V344_UNSHADED_COLOR_CONTRACT")
            _whole_extent(p, tiles)
        relation_map = {}
        for r in self.relations:
            if r.source not in parts or r.target not in parts or r.proof_label_id not in labels:
                raise ValueError("V344_RELATION_DANGLING_REFERENCE")
            src,dst = parts[r.source],parts[r.target]
            if not (src.numerator*r.multiply_by == dst.numerator and
                    src.denominator*r.multiply_by == dst.denominator and
                    Fraction(src.numerator,src.denominator) == Fraction(dst.numerator,dst.denominator)):
                raise ValueError("V344_UNGROUNDED_RATIO_TRANSFORMATION")
            a,b = _whole_extent(src,tiles)[0],_whole_extent(dst,tiles)[0]
            if abs(a-b)/b > .05:
                raise ValueError("V344_DIFFERENT_SIZED_WHOLES")
            expected = f"({src.numerator}×{r.multiply_by})/({src.denominator}×{r.multiply_by}) = {dst.numerator}/{dst.denominator}"
            if labels[r.proof_label_id].text != expected:
                raise ValueError("V344_MISSING_EXPLICIT_ALGEBRA_PROOF")
            relation_map[(r.source,r.target)] = r
        # Numeric screen text must come from a validated fraction or a
        # relational proof. Arbitrary numeric labels would bypass the source
        # factual contract even if geometric fractions are mathematically valid.
        valid_fraction_labels = {
            f"{p.numerator}/{p.denominator}" for p in self.partitions
        }
        allowed_arithmetic = valid_fraction_labels | {
            labels[r.proof_label_id].text for r in self.relations
        }
        for label in self.labels:
            if re.search(r"\d", label.text) and label.text not in allowed_arithmetic:
                raise ValueError("V344_UNGROUNDED_VISIBLE_NUMERIC_LABEL")
        visible_groups, visible_labels = set(), set()
        used_proof, used_morph = set(), set()
        for beat in self.beats:
            prev_end = 0.
            for e in beat.events:
                if e.at < prev_end-1e-5:
                    raise ValueError("V344_EVENT_OVERLAP")
                prev_end = e.at+e.span
                if e.kind == "reveal_partition":
                    if e.target not in parts or e.target in visible_groups:
                        raise ValueError("V344_INVALID_GROUP_REVEAL")
                    visible_groups.add(e.target)
                elif e.kind == "morph_partition":
                    if (e.source,e.target) not in relation_map or e.source not in visible_groups or e.target in visible_groups:
                        raise ValueError("V344_MORPH_NOT_SOURCE_GROUNDED")
                    visible_groups.add(e.target)
                    used_morph.add((e.source,e.target))
                elif e.kind == "show_label":
                    if e.target not in labels or e.target in visible_labels:
                        raise ValueError("V344_LABEL_NOT_DECLARED_OR_ALREADY_SHOWN")
                    visible_labels.add(e.target)
                    if e.target in {r.proof_label_id for r in self.relations}:
                        if "F2" not in beat.claim_ids:
                            raise ValueError("V344_PROOF_NOT_BOUND_TO_ARITHMETIC_CLAIM")
                        used_proof.add(e.target)
                elif e.kind == "emphasize":
                    if e.target not in visible_groups | visible_labels:
                        raise ValueError("V344_HIGHLIGHT_BEFORE_VISIBLE")
        if used_morph != set(relation_map) or used_proof != {r.proof_label_id for r in self.relations}:
            raise ValueError("V344_REQUIRED_SEMANTIC_MORPH_OR_PROOF_NOT_SHOWN")
        if {claim for beat in self.beats for claim in beat.claim_ids} != {"F1","F2","F3"}:
            raise ValueError("V344_FROZEN_FACT_COVERAGE_DRIFT")
        return self


